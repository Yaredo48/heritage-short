"""Summarise runs.jsonl into the measured table in COSTS.md.

Only real log lines are counted. The list-price column uses the prices noted
below; anything we could not price is left blank rather than guessed.

Run: python run.py costs
"""
from __future__ import annotations

import json
from collections import defaultdict

from . import common
from .common import ROOT

START, END = "<!-- costs:start -->", "<!-- costs:end -->"
# Assumption for a list-price equivalent of free Kaggle GPU time: an on-demand
# NVIDIA T4 on a public cloud, about USD 0.35 per GPU-hour. Check before quoting.
T4_USD_PER_HOUR = 0.35


def summarise(lines: list[dict]) -> list[dict]:
    groups: dict[tuple, dict] = defaultdict(lambda: {"ok": 0, "error": 0, "cache_hits": 0, "latency": [],
                                                     "usd": 0.0, "gpu_min": 0.0, "priced": False})
    for rec in lines:
        if rec.get("event") == "cache_hit":
            groups[(rec["stage"], "(cache)")]["cache_hits"] += 1
            continue
        if rec.get("event") != "model_call":
            continue
        g = groups[(rec["stage"], f"{rec.get('provider')}/{rec.get('model')}")]
        g["ok" if rec.get("status") == "ok" else "error"] += 1
        if rec.get("status") == "ok":
            g["latency"].append(rec.get("latency_s", 0))
        cost = rec.get("cost") or {}
        if "usd_list_est" in cost:
            g["usd"] += cost["usd_list_est"]
            g["priced"] = True
        if "gpu_minutes" in cost:
            g["gpu_min"] += cost["gpu_minutes"]
            g["usd"] += cost["gpu_minutes"] / 60 * T4_USD_PER_HOUR
            g["priced"] = True
    rows = []
    for (stage, model), g in sorted(groups.items()):
        lat = g["latency"]
        rows.append({"stage": stage, "model": model, "ok": g["ok"], "errors": g["error"],
                     "cache_hits": g["cache_hits"],
                     "mean_latency_s": round(sum(lat) / len(lat), 2) if lat else None,
                     "total_latency_s": round(sum(lat), 1) if lat else None,
                     "gpu_minutes": round(g["gpu_min"], 1) if g["gpu_min"] else None,
                     "usd_list_equiv": round(g["usd"], 4) if g["priced"] else None})
    return rows


def table(rows: list[dict]) -> str:
    head = ("| Stage | Provider / model | OK calls | Failed attempts | Cache hits | Mean latency (s) "
            "| Total latency (s) | GPU min | List-price equiv. (USD) |\n|---|---|---|---|---|---|---|---|---|")
    fmt = lambda v: "" if v is None else str(v)  # noqa: E731
    body = [f"| {r['stage']} | {r['model']} | {r['ok']} | {r['errors']} | {r['cache_hits']} | "
            f"{fmt(r['mean_latency_s'])} | {fmt(r['total_latency_s'])} | {fmt(r['gpu_minutes'])} | "
            f"{fmt(r['usd_list_equiv'])} |" for r in rows]
    return "\n".join([head, *body])


def main(command, args):
    lines = [json.loads(l) for l in common.RUNS_LOG.read_text(encoding="utf-8").splitlines() if l.strip()]
    rows = summarise(lines)
    md = table(rows)
    print(md)
    costs = ROOT / "COSTS.md"
    if costs.exists() and START in costs.read_text(encoding="utf-8"):
        text = costs.read_text(encoding="utf-8")
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        costs.write_text(f"{before}{START}\n_Generated by `make costs` from {len(lines)} lines of "
                         f"runs.jsonl._\n\n{md}\n{END}{after}", encoding="utf-8")
        print("\nupdated COSTS.md")
